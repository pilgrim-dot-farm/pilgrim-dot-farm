#!/usr/bin/env bash
# Model fleet watchdog on the Mac Studio (docs/systems/model-fleet.md §6).
# launchd runs one `fleetctl watch` pass every minute; the pass restarts any
# model whose `pg-<service>` tmux session or /health is gone.
#
#   pilgrim/deploy/mac/fleet.sh install    # render + load the launchd agent
#   pilgrim/deploy/mac/fleet.sh status
#   pilgrim/deploy/mac/fleet.sh uninstall
#
# No secrets: the watchdog only uses ssh (keys in ~/.ssh) and curl /health.
set -euo pipefail

ROOT=$(cd "$(dirname "$0")/../../.." && pwd)
PY="$ROOT/.venv/bin/python"
LOGS="$HOME/Library/Logs/pilgrim"
AGENTS="$HOME/Library/LaunchAgents"
LABEL=farm.pilgrim.fleet
PLIST="$AGENTS/$LABEL.plist"
INTERVAL="${FLEET_INTERVAL_S:-60}"
UID_=$(id -u)

render() {
    mkdir -p "$LOGS" "$AGENTS"
    cat > "$PLIST" <<EOF
<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<!-- Generated by pilgrim/deploy/mac/fleet.sh. No secrets here. -->
<plist version="1.0">
<dict>
  <key>Label</key><string>$LABEL</string>
  <key>ProgramArguments</key>
  <array>
    <string>$PY</string><string>-m</string><string>pilgrim.tools.fleetctl</string><string>watch</string>
  </array>
  <key>WorkingDirectory</key><string>$ROOT</string>
  <key>EnvironmentVariables</key>
  <dict>
    <key>PATH</key><string>/opt/homebrew/bin:/usr/local/bin:/usr/bin:/bin:/usr/sbin:/sbin</string>
  </dict>
  <key>StartInterval</key><integer>$INTERVAL</integer>
  <key>RunAtLoad</key><true/>
  <!-- tmux sessions the pass starts must outlive the pass -->
  <key>AbandonProcessGroup</key><true/>
  <key>StandardOutPath</key><string>$LOGS/fleet.log</string>
  <key>StandardErrorPath</key><string>$LOGS/fleet.err.log</string>
</dict>
</plist>
EOF
}

case "${1:-status}" in
    install)
        render
        launchctl bootout "gui/$UID_/$LABEL" 2>/dev/null || true
        launchctl bootstrap "gui/$UID_" "$PLIST"
        echo "installed $LABEL (every ${INTERVAL}s); log: $LOGS/fleet.log"
        ;;
    uninstall)
        launchctl bootout "gui/$UID_/$LABEL" 2>/dev/null || true
        rm -f "$PLIST"
        echo "removed $LABEL"
        ;;
    status)
        launchctl print "gui/$UID_/$LABEL" 2>/dev/null | grep -E "state|last exit|runs" \
            || echo "$LABEL: not installed"
        ( cd "$ROOT" && "$PY" -m pilgrim.tools.fleetctl status ) || true
        [ -f "$LOGS/fleet.log" ] && tail -5 "$LOGS/fleet.log"
        ;;
    *) echo "usage: $0 {install|status|uninstall}" >&2; exit 2 ;;
esac
